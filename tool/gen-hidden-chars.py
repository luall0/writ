#!/usr/bin/env python3
"""Generates crates/writ-core/src/text/hidden.rs: the characters `writ sign` must never let
through as they are (writ_core::text::is_hidden_char).

The set is derived, never hand-maintained:
- every character in the general categories Cc (controls), Cf (format: bidi, zero-width,
  tags...), Co (private use), Cn (unassigned: escaped until a reviewed table says otherwise),
  Cs (surrogates), Zl and Zp (line and paragraph separators);
- plus the Default_Ignorable_Code_Point characters outside those categories (variation
  selectors, Hangul fillers, the combining grapheme joiner, Khmer and Mongolian invisibles,
  the tag block), which render as nothing (Unicode DerivedCoreProperties.txt; Python's
  unicodedata doesn't expose the property, so the list is below).

Run by hand after a Python upgrade brings a newer Unicode version:
    python3 -I tool/gen-hidden-chars.py
"""

import pathlib
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "crates/writ-core/src/text/hidden.rs"
CATEGORIES = {"Cc", "Cf", "Co", "Cn", "Cs", "Zl", "Zp"}
# Default_Ignorable_Code_Point not in the categories above (DerivedCoreProperties.txt).
DEFAULT_IGNORABLE_EXTRA = [
    (0x00AD, 0x00AD),  # soft hyphen (Cf already, kept for clarity)
    (0x034F, 0x034F),  # combining grapheme joiner
    (0x115F, 0x1160),  # Hangul choseong and jungseong fillers
    (0x17B4, 0x17B5),  # Khmer inherent vowels
    (0x180B, 0x180F),  # Mongolian free variation selectors and vowel separator
    (0x3164, 0x3164),  # Hangul filler
    (0xFE00, 0xFE0F),  # variation selectors
    (0xFFA0, 0xFFA0),  # halfwidth Hangul filler
    (0x1BCA0, 0x1BCA3),  # shorthand format controls
    (0x1D173, 0x1D17A),  # musical symbol formatting
    (0xE0000, 0xE0FFF),  # tags and variation selectors supplement
]


def hidden(code: int) -> bool:
    if unicodedata.category(chr(code)) in CATEGORIES:
        return True
    return any(lo <= code <= hi for lo, hi in DEFAULT_IGNORABLE_EXTRA)


def ranges():
    out = []
    start = None
    for code in range(0x110000):
        if hidden(code):
            if start is None:
                start = code
        elif start is not None:
            out.append((start, code - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main() -> int:
    found = ranges()
    lines = [
        "//! Generated by `tool/gen-hidden-chars.py` from Unicode "
        f"{unicodedata.unidata_version}: do not edit by hand.",
        "//!",
        "//! Every code point in the general categories Cc, Cf, Co, Cn, Cs, Zl, Zp, plus the",
        "//! Default_Ignorable_Code_Point characters outside them, as sorted inclusive ranges.",
        "",
        "pub(super) const HIDDEN: &[(u32, u32)] = &[",
    ]
    lines += [f"    (0x{lo:04X}, 0x{hi:04X})," for lo, hi in found]
    lines += ["];", ""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(ROOT)}: {len(found)} ranges (Unicode {unicodedata.unidata_version})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
